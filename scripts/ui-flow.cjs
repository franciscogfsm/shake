// Drives the real UI on two phones: buyer creates + locks, seller joins + shows QR, buyer scans code + holds to shake.
const { chromium } = require('playwright');
const B = process.argv[2] || 'http://localhost:3100', OUT = process.argv[3];
const t0 = Date.now(); const lap = (m) => console.log(((Date.now() - t0) / 1000).toFixed(1) + 's', m);
(async () => {
  const br = await chromium.launch();
  const mk = async () => { const c = await br.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, hasTouch: false }); const p = await c.newPage(); p.on('pageerror', e => console.log('PAGEERROR', e.message)); return p; };
  const buyer = await mk(), seller = await mk();
  await buyer.goto(B + '/deal/new', { timeout: 180000 });
  await buyer.fill('#item', 'Nintendo Switch');
  await buyer.fill('#price', '12');
  await buyer.screenshot({ path: OUT + '/f1-new-filled.png' });
  await buyer.click('button[type=submit]');
  await buyer.waitForTimeout(1500); await buyer.screenshot({ path: OUT + '/f2-locking.png' });
  await buyer.waitForURL(/\/deal\/\d+/, { timeout: 120000 });
  lap('locked → ' + buyer.url());
  await buyer.waitForTimeout(2500); await buyer.screenshot({ path: OUT + '/f3-share.png' });
  const id = buyer.url().match(/deal\/(\d+)/)[1];
  const link = buyer.url().replace('&new=1', '').replace('new=1', '');
  await seller.goto(link, { timeout: 180000 });
  await seller.getByText("I'm meeting them").waitFor({ timeout: 60000 });
  await seller.waitForTimeout(1500); await seller.screenshot({ path: OUT + '/f4-seller.png' });
  await seller.getByText("I'm meeting them").click();
  await seller.getByText('Let the buyer scan this.').waitFor({ timeout: 120000 });
  lap('seller joined, QR shown');
  await seller.waitForTimeout(1200); await seller.screenshot({ path: OUT + '/f5-qr.png' });
  const code = await seller.evaluate((id) => localStorage.getItem('shake.code.' + id), id);
  lap('code ' + code);
  await buyer.goto(`${B}/scan/${id}`, { timeout: 180000 });
  await buyer.fill('#code', code);
  await buyer.screenshot({ path: OUT + '/f6-scan.png' });
  await buyer.getByRole('button', { name: 'Go' }).click();
  const hold = buyer.getByRole('button', { name: 'Hold to shake' });
  await hold.waitFor({ timeout: 30000 });
  await buyer.waitForTimeout(600); await buyer.screenshot({ path: OUT + '/f7-confirm.png' });
  const box = await hold.boundingBox();
  await buyer.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await buyer.mouse.down(); await buyer.waitForTimeout(700); await buyer.screenshot({ path: OUT + '/f8-holding.png' });
  await buyer.waitForTimeout(1000); await buyer.mouse.up();
  lap('held');
  await buyer.getByText('Shaken.').waitFor({ timeout: 90000 });
  lap('released (buyer)'); await buyer.screenshot({ path: OUT + '/f9-shaken.png' });
  await seller.getByText('Paid to you').waitFor({ timeout: 60000 });
  lap('seller sees it'); await seller.waitForTimeout(1200); await seller.screenshot({ path: OUT + '/f10-seller-paid.png' });
  await br.close(); console.log('UI FLOW OK');
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
